class Command(BaseCommand):
    help = "Заполнить начальные тексты бота в БД (BotText)"

    def add_arguments(self, parser):
        parser.add_argument(
            "--force",
            action="store_true",
            help="Перезаписать существующие тексты",
        )

    def handle(self, *args, **options):
        force = options["force"]
        created = 0
        skipped = 0
        updated = 0

        for key, (text, description) in BOT_TEXTS.items():
            obj, was_created = BotText.objects.get_or_create(
                key=key,
                channel="telegram",
                locale="ru",
                defaults={"text": text, "description": description, "is_active": True},
            )
            if was_created:
                created += 1
                self.stdout.write(self.style.SUCCESS(f"  ✅ Создан: {key}"))
            elif force:
                obj.text = text
                obj.description = description
                obj.save(update_fields=["text", "description"])
                updated += 1
                self.stdout.write(self.style.WARNING(f"  ♻️  Обновлён: {key}"))
            else:
                skipped += 1

        self.stdout.write(
            self.style.SUCCESS(
                f"\nГотово: создано={created}, обновлено={updated}, пропущено={skipped}."
            )
        )
